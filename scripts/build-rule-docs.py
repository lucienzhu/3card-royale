#!/usr/bin/env python3
"""Generate translated GitHub rulebooks from the same copy as the web rulebook."""
import argparse
from html.parser import HTMLParser
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
LANGUAGES = {'ja': '日本語', 'ko': '한국어', 'es': 'Español'}


class MarkdownRules(HTMLParser):
    def __init__(self):
        super().__init__()
        self.parts = []
        self.item = 0
        self.header_row = False
        self.columns = 0

    def handle_starttag(self, tag, attrs):
        if tag in ('h1', 'h2'):
            self.parts.append('\n\n' + '#' * int(tag[1]) + ' ')
        elif tag in ('p', 'ol', 'table'):
            self.parts.append('\n\n')
            if tag == 'ol':
                self.item = 0
        elif tag == 'li':
            self.item += 1
            self.parts.append(f'\n{self.item}. ')
        elif tag == 'strong':
            self.parts.append('**')
        elif tag == 'tr':
            self.parts.append('\n| ')
            self.header_row = False
            self.columns = 0
        elif tag == 'th':
            self.header_row = True
            self.columns += 1

    def handle_endtag(self, tag):
        if tag in ('h1', 'h2', 'p', 'ol', 'table'):
            self.parts.append('\n\n')
        elif tag == 'strong':
            self.parts.append('**')
        elif tag in ('td', 'th'):
            self.parts.append(' | ')
        elif tag == 'tr' and self.header_row:
            self.parts.append('\n| ' + ' | '.join(['---'] * self.columns) + ' |')

    def handle_data(self, text):
        self.parts.append(text.replace('|', '\\|'))


def render(locale, html):
    parser = MarkdownRules()
    parser.feed(html)
    body = re.sub(r'\n{3,}', '\n\n', ''.join(parser.parts)).strip()
    body = '\n'.join(line.rstrip() for line in body.splitlines())
    title, rest = body.split('\n', 1)
    links = '[English](RULES.md) · [简体中文](RULES.zh-CN.md) · ' + ' · '.join(
        f'**{name}**' if code == locale else f'[{name}](RULES.{code}.md)'
        for code, name in LANGUAGES.items())
    extras = {
        'ja': '技術ガイド', 'ko': '기술 가이드', 'es': 'Guía técnica',
    }
    return (f'{title}\n\n<!-- doc-navigation:start -->\n{links}\n\n'
            f'[A4 PDF](shenzhen-flower-rules-a4.{locale}.pdf) · '
            f'[{extras[locale]}](GUIDE.{locale}.md)\n<!-- doc-navigation:end -->\n\n'
            '<!-- Generated by scripts/build-rule-docs.py from app/locales/rules.js. -->\n\n'
            + rest.strip() + '\n')


def main():
    args = argparse.ArgumentParser()
    args.add_argument('--check', action='store_true')
    check = args.parse_args().check
    source = (ROOT / 'app/locales/rules.js').read_text()
    rules = json.loads(source[source.index('{'):source.rindex('}') + 1])
    for locale in LANGUAGES:
        output = ROOT / f'docs/RULES.{locale}.md'
        result = render(locale, rules[locale])
        if check:
            if not output.exists() or output.read_text() != result:
                raise SystemExit(f'Stale translated rulebook: {output.name}')
        else:
            output.write_text(result)
        print(output.name)


if __name__ == '__main__':
    main()
